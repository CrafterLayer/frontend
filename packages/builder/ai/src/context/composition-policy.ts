/**
 * The single per-run dial for how much freedom the assistant gets and how much
 * the run costs.
 *
 * ## Why one object instead of parameters
 *
 * Every knob here starts life as `undefined`, and every `undefined` resolves to
 * the FREEST behaviour that still works. That is the property that makes this
 * surface additive forever: a future guard arrives as one more optional key
 * whose absence means "as before", so tightening a policy later is a value
 * change at a call site rather than a signature change through four layers.
 *
 * The alternative — a boolean threaded through `assembleAiContext`,
 * `generateAiPlan`, and `runAiAgent` for each decision — was rejected because
 * the third such boolean would have made every one of those signatures churn.
 *
 * The policy is passed IN, never read from module state. Two runs in the same
 * process may disagree about their limits, which is what makes per-tenant and
 * per-session configuration possible without a global.
 */

/** How much of the block registry crosses the wire. */
export type AiCatalogMode =
  /**
   * NO catalog. Only the always-detailed escape hatch (`customCode`) and the
   * types named in `scopedBlockTypes` cross the wire, each in full; every
   * other registered block is absent — not even its name.
   *
   * This is "the model builds the page itself": from elements, the utility
   * vocabulary, and scoped CSS. A registered block enters the model's world
   * only when the person ADDS it to the request — by selecting it or
   * mentioning it — and then it arrives with its whole schema, usable as a
   * `component` reference inside the composition. The input is what the
   * person wants from the site, not an inventory of what exists.
   */
  | 'none'
  /**
   * Type and description for every registered block; no schemas, examples, or
   * slot tables. The model still knows the whole vocabulary and can ask for a
   * type by name — it just cannot fill that type's props from context alone.
   */
  | 'index'
  /**
   * `index` for the whole registry, plus full detail for the types named in
   * `scopedBlockTypes`. This is the shape of "the user selected this block and
   * asked to change it": the model gets everything about the thing in hand and
   * a name-level map of everything else.
   */
  | 'scoped'
  /**
   * Full detail for every registered block — the behaviour that predates this
   * policy, kept as the default so no existing caller silently loses schemas.
   */
  | 'full';

export interface AiCompositionPolicy {
  /**
   * Defaults to `'full'`.
   *
   * The default is deliberately the expensive one. A cheaper default would be
   * correct only once the assistant has a way to build without per-block
   * schemas; until then, dropping them would trade cost for a broken proposal,
   * which is not a trade the library may make on a caller's behalf. Hosts that
   * are ready opt in explicitly.
   */
  readonly catalogMode?: AiCatalogMode;
  /**
   * Types expanded to full detail under `'scoped'` and `'none'`; ignored in
   * other modes. Unregistered names are skipped rather than surfaced as empty
   * entries — a catalog entry the registry cannot back is a block the model
   * would propose and the door would reject.
   */
  readonly scopedBlockTypes?: readonly string[];
  /**
   * Types that keep full detail in EVERY mode. Defaults to
   * `DEFAULT_ALWAYS_DETAILED_BLOCK_TYPES`.
   *
   * A cheap catalog trades per-block schemas for the ability to compose freely
   * instead — but that trade only holds if the block the model composes WITH
   * is itself authorable. Left to the ordinary rule, `customCode` would arrive
   * in `index` mode as a name and a sentence: the model would know an escape
   * hatch exists and have no way to write one, which is strictly worse than
   * either endpoint. So the escape hatch is exempt from the very economy it
   * makes possible.
   *
   * Pass an empty array to opt out entirely; pass your own list to extend it.
   */
  readonly alwaysDetailedBlockTypes?: readonly string[];
  /**
   * Refuse a plan whose custom-code tree writes a class name outside the
   * runtime utility vocabulary. Defaults to `true`.
   *
   * This is the one guard whose default is the STRICT setting, and the reason
   * is that the permissive behaviour is not "more freedom" — it is silence. A
   * class Tailwind never generated has no CSS at all: it works in dev if some
   * other file happens to mention it, vanishes in the production build, and
   * reports nothing either way. Refusing at the door turns that into a named
   * validation issue on the proposal that caused it.
   *
   * Set it false only where the CSS is generated by something other than this
   * workspace's vocabulary — a host with its own stylesheet, for instance.
   */
  readonly enforceUtilityVocabulary?: boolean;
  /**
   * Whether a custom-code tree may use colours outside the site's roles.
   * Defaults to `'free'`.
   *
   * `'free'`: Tailwind's palette classes (`bg-blue-600`) and exact values in
   * the region's `css` (`#1e3a8a`, `rgb()`) are allowed. Such colours do not
   * follow the site theme — re-point `--t-accent` and they stay put — and the
   * product's owner chose that trade: an assistant asked for "a travel
   * background with white text" must be able to make one.
   *
   * `'tokens'`: the theming law applies to trees exactly as it does to a
   * registered block's `className` prop — roles only, no palette, no hex.
   */
  readonly colourPolicy?: 'free' | 'tokens';
  /**
   * How much of an ALREADY-COMPOSED region's tree the document context carries.
   * Defaults to `'full'`.
   *
   * `'full'`: every node's full props, as before — the page's own words are
   * readable, which is what makes "change the word X" answerable at all.
   *
   * `'scoped'`: the regions named in `treeScopeNodeIds` keep their whole tree;
   * every other custom-code tree is replaced by a shape summary (its node
   * count and its heading, never its body). Meant for a run that edits ONE
   * region of a long page: the ten-section build re-shipped every section's
   * tree on every step, so filling the last section cost several times what
   * filling the first did, for text the model was told not to touch.
   *
   * It trims TREES only. Every node keeps its id, type, slots and ordinary
   * props, so the page's shape is never hidden — only the interior of regions
   * the run was told to leave alone.
   */
  readonly documentTreeMode?: 'full' | 'scoped';
  /**
   * Node ids whose trees survive under `documentTreeMode: 'scoped'`; ignored
   * in `'full'`. Absent means the run's own selection is used.
   */
  readonly treeScopeNodeIds?: readonly string[];
}

/** The resolved policy: every optional decided exactly once, at the edge. */
export interface ResolvedAiCompositionPolicy {
  readonly catalogMode: AiCatalogMode;
  readonly scopedBlockTypes: ReadonlySet<string>;
  readonly alwaysDetailedBlockTypes: ReadonlySet<string>;
  readonly enforceUtilityVocabulary: boolean;
  readonly colourPolicy: 'free' | 'tokens';
  readonly documentTreeMode: 'full' | 'scoped';
  readonly treeScopeNodeIds: ReadonlySet<string>;
}

/**
 * The blocks that stay authorable however cheap the catalog gets.
 *
 * One entry, and it earns its place by being the block every other block's
 * absence is answered WITH: when the catalog states only names, `customCode`
 * is how the model builds anything at all.
 */
export const DEFAULT_ALWAYS_DETAILED_BLOCK_TYPES: readonly string[] = Object.freeze(['customCode']);

const NO_SCOPED_TYPES: ReadonlySet<string> = Object.freeze(new Set<string>());
const NO_SCOPED_NODE_IDS: ReadonlySet<string> = Object.freeze(new Set<string>());

/**
 * Resolve once, at the assembly boundary, so no downstream code re-derives a
 * default. A second resolution site is a second place for the defaults to
 * drift, and drifting defaults are invisible until a bill arrives.
 */
export function resolveAiCompositionPolicy(
  policy: AiCompositionPolicy | undefined,
): ResolvedAiCompositionPolicy {
  const catalogMode = policy?.catalogMode ?? 'full';
  return {
    catalogMode,
    scopedBlockTypes:
      (catalogMode === 'scoped' || catalogMode === 'none') && policy?.scopedBlockTypes !== undefined
        ? Object.freeze(new Set(policy.scopedBlockTypes))
        : NO_SCOPED_TYPES,
    alwaysDetailedBlockTypes: Object.freeze(
      new Set(policy?.alwaysDetailedBlockTypes ?? DEFAULT_ALWAYS_DETAILED_BLOCK_TYPES),
    ),
    enforceUtilityVocabulary: policy?.enforceUtilityVocabulary ?? true,
    colourPolicy: policy?.colourPolicy ?? 'free',
    documentTreeMode: policy?.documentTreeMode ?? 'full',
    treeScopeNodeIds:
      policy?.treeScopeNodeIds === undefined
        ? NO_SCOPED_NODE_IDS
        : Object.freeze(new Set(policy.treeScopeNodeIds)),
  };
}

/** Whether this block's detail fields belong in the assembled context. */
export function blockIsInCatalogScope(policy: ResolvedAiCompositionPolicy, type: string): boolean {
  if (policy.alwaysDetailedBlockTypes.has(type)) return true;
  switch (policy.catalogMode) {
    case 'full':
      return true;
    case 'scoped':
    case 'none':
      return policy.scopedBlockTypes.has(type);
    case 'index':
      return false;
  }
}
