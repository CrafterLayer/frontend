/**
 * The verified photo catalog, as DATA.
 *
 * ## Why a catalog at all
 *
 * Measured 2026-09-28 over 76 recorded answers: 13% carried any image, and 10
 * of the 14 distinct photos the model chose were the same memorised Western
 * stock portraits, set beside invented Arabic customer names. Every builder
 * that avoids broken or wrong pictures (v0, Emergent, dyad, open-lovable, this
 * package's own `select-assets.ts`) feeds real URLs from OUTSIDE the model's
 * memory. A skill sentence ("use valid URLs") does not; bolt says exactly that
 * and still hallucinates.
 *
 * ## Where these came from, and how they were checked
 *
 * Seeded by the page-power research pass (scratchpad `research/photos/
 * catalog.v0.json`): Pexels photos found through web search (the Pexels and
 * Unsplash search pages refuse bots), each CDN URL fetched — 200, image/jpeg —
 * and every one looked at on a contact sheet, then given alt text in both
 * languages from what is actually in the picture. Re-fetched 78/78 on
 * 2026-09-28 before landing here. Never derive a Pexels URL from an id without
 * fetching it: ids 919 and 5944 404 under the derived filename.
 *
 * `people` was read off the same contact sheet: `faces` means a visitor sees a
 * stranger's face, which must never stand beside an invented name or quote.
 *
 * Licence: the Pexels License — free commercial use, no attribution required,
 * no resale of unaltered copies. `page` keeps each photo's provenance.
 */

