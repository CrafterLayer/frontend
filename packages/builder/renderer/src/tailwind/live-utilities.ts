import { buildTailwindThemeCss } from './token-bridge';

/**
 * Tailwind's own compiler, running in the page, generating CSS for exactly
 * the classes a document uses.
 *
 * ## The failure this removes
 *
 * A static build generates only the classes it can see, so the assistant was
 * held to a precomputed vocabulary of ~10k names. Ordinary Tailwind fell
 * outside it — `md:flex-row`, `backdrop-blur`, `border-emerald-900/20`, every
 * arbitrary value — and a section that used one was refused whole and sent
 * back to the model (measured 2026-09-27: a 25-40 second repair round for one
 * class). The skills had grown a list of "refused" classes to steer around it,
 * which then went stale and told the model to avoid classes that worked.
 *
 * With the compiler in the page, the class names a tree carries ARE the
 * stylesheet: whatever Tailwind can generate renders, on the canvas and in
 * preview, and the door asks this same compiler whether a name is real. One
 * engine decides what exists, so the door and the canvas cannot disagree.
 *
 * ## Why this shape
 *
 * - Utilities and theme only, never preflight: the host page already carries
 *   Tailwind's base layer, and a second reset would restyle the editor chrome.
 * - The site's `@theme` door is generated by `buildTailwindThemeCss`, the same
 *   generator as the static `tailwind.css`, so `bg-accent` still resolves
 *   through `--t-accent` and a re-themed site still re-themes.
 * - The generated sheet is REPLACED on every change, not rewritten: the canvas
 *   iframe mirrors host style NODES as they are inserted (CanvasFrame), not
 *   later edits to their text.
 * - Tailwind is imported lazily, so a host that never registers this pays
 *   nothing for it.
 */
export interface LiveUtilities {
  /** Whether Tailwind generates CSS for this one class — the oracle the door consults. */
  readonly isUtilityClass: (name: string) => boolean;
  /** Generate CSS for these classes, together with every class asked for before. */
  readonly ensure: (classNames: Iterable<string>) => void;
  /** The stylesheet generated so far. */
  readonly css: () => string;
  /** Remove the generated stylesheet. */
  readonly dispose: () => void;
}

export interface LiveUtilitiesOptions {
  /** The document the stylesheet is written into; absent ⇒ generate only. */
  readonly document?: Document | undefined;
  /**
   * The text of `tailwindcss/theme.css` — Tailwind's default scale, palette
   * and breakpoints. The host supplies it (a Vite app imports it with `?raw`)
   * because only the host's bundler can turn a stylesheet into a string.
   */
  readonly tailwindThemeCss: string;
}

const ENTRY = [
  "@import 'tailwindcss/theme.css' layer(theme);",
  "@import 'tailwindcss/utilities.css' layer(utilities);",
  "@import 'craftkit/theme.css';",
].join('\n');

const STYLE_ATTRIBUTE = 'data-ck-live-utilities';

/**
 * `group` and `peer` generate no CSS of their own — they are the markers that
 * `group-hover:` and `peer-checked:` select on — so the compiler reports them
 * as nothing. Refusing them would silently break every hover effect built on
 * them.
 */
const MARKER_CLASS = /^(?:group|peer)(?:\/[A-Za-z0-9_-]+)?$/u;

/** A verdict cache bound: class names are finite in practice, but input is not trusted. */
const MAX_VERDICTS = 50_000;

export async function createLiveUtilities(options: LiveUtilitiesOptions): Promise<LiveUtilities> {
  const tailwind = await import('tailwindcss');
  const themeCss = options.tailwindThemeCss;
  /*
    A theme without breakpoints compiles without complaint and then judges
    every `md:` class unknown — so a host whose bundler handed over an empty
    file (Vitest does, for CSS) must fail HERE and keep its static vocabulary,
    not run a compiler that quietly refuses half of Tailwind.
  */
  if (!themeCss.includes('--breakpoint-md')) {
    throw new Error(
      "Live utilities need Tailwind's theme.css; the one provided has no breakpoints.",
    );
  }
  const sources: Readonly<Record<string, string>> = {
    'tailwindcss/theme.css': themeCss,
    'tailwindcss/utilities.css': '@tailwind utilities;',
    'craftkit/theme.css': buildTailwindThemeCss(),
  };
  const loadStylesheet = (id: string, base: string) => {
    const content = sources[id];
    if (content === undefined) {
      return Promise.reject(new Error(`Live utilities cannot load the stylesheet "${id}".`));
    }
    return Promise.resolve({ path: id, base, content });
  };
  const [compiler, design] = await Promise.all([
    tailwind.compile(ENTRY, { loadStylesheet }),
    tailwind.__unstable__loadDesignSystem(ENTRY, { loadStylesheet }),
  ]);

  const verdicts = new Map<string, boolean>();
  const built = new Set<string>();
  let generated = '';
  let sheet: HTMLStyleElement | undefined;

  const isUtilityClass = (name: string): boolean => {
    const known = verdicts.get(name);
    if (known !== undefined) return known;
    const verdict =
      name.trim() === name &&
      name !== '' &&
      (MARKER_CLASS.test(name) || design.candidatesToCss([name])[0] !== null);
    if (verdicts.size < MAX_VERDICTS) verdicts.set(name, verdict);
    return verdict;
  };

  const write = (): void => {
    const target = options.document;
    if (target === undefined) return;
    const next = target.createElement('style');
    next.setAttribute(STYLE_ATTRIBUTE, '');
    next.textContent = generated;
    target.head.appendChild(next);
    sheet?.remove();
    sheet = next;
  };

  return {
    isUtilityClass,
    ensure: (classNames) => {
      let grew = false;
      for (const name of classNames) {
        if (built.has(name) || MARKER_CLASS.test(name) || !isUtilityClass(name)) continue;
        built.add(name);
        grew = true;
      }
      if (!grew) return;
      generated = compiler.build([...built]);
      write();
    },
    css: () => generated,
    dispose: () => {
      sheet?.remove();
      sheet = undefined;
    },
  };
}
