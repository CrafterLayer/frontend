/**
 * A schema property's or section's name in the editor's language: the Arabic
 * entry when there is one, else `english` (the humanised key the English
 * chrome already shows).
 */
export function schemaName(word: string, locale: EditorLocale, english: string = word): string {
  if (locale !== 'ar') return english;
  return SCHEMA_NAMES_AR[schemaWordKey(word)] ?? english;
}

/** An enum option as a list shows it: Arabic when known, else the option itself. */
export function schemaOption(option: string, locale: EditorLocale): string {
  if (locale !== 'ar') return option;
  return SCHEMA_OPTIONS_AR[schemaWordKey(option)] ?? option;
}
