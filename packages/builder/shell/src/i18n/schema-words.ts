/*
  ── What the Inspector calls a block's own words, per language ───────────────

  A block schema is written once, in English code words: its property keys
  (`eyebrow`, `trustLine`), its section names (`Text`, `Layout`) and its enum
  options (`lg`, `transparent`, `full`). The English chrome humanises them;
  the Arabic chrome showed them as they are, so a person working in Arabic
  read "TEXT · Eyebrow · Heading" and picked "transparent" from a list (walk
  2026-10-08).

  This is the Arabic table for the words the shipped extensions use. Keys are
  normalised the way block names are (lower case, letters and digits only),
  so `trustLine`, `trust-line` and `Trust line` find the same entry. A word
  the table does not know keeps its English form rather than inventing one.
*/
import type { EditorLocale } from './editor-locale';
import { SCHEMA_OPTIONS_AR } from './schema-options-ar';

export { SCHEMA_OPTIONS_AR };

/** `trustLine` / `Trust line` / `Padding & margin` → `trustline` / `paddingmargin`. */
export function schemaWordKey(text: string): string {
  return text.replace(/[^a-zA-Z0-9]/gu, '').toLowerCase();
}

