#!/usr/bin/env node
// Mechanical generation of one licensed, standalone, lazy asset (never the editor main chunk).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const owner = join(root, 'packages/builder/extensions/media-engines');
const require = createRequire(join(owner, 'package.json'));
const { build } = require('esbuild');
const manifestPath = require.resolve('embla-carousel/package.json');
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
if (manifest.version !== '8.6.0' || manifest.license !== 'MIT')
  throw new Error('Re-audit the pinned Embla release before building.');
const license = readFileSync(join(owner, 'vendor/embla-carousel/LICENSE'), 'utf8');
if (!license.includes('MIT License')) throw new Error('Missing Embla MIT license text.');
const built = await build({
  entryPoints: [join(owner, 'src/carousel-entry.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'inline',
  metafile: true,
  logLevel: 'silent',
});
// Embla is dependency-free. Fail closed if another third-party package enters this asset.
for (const input of Object.keys(built.metafile.inputs)) {
  if (input.includes('node_modules') && !input.includes('/embla-carousel/'))
    throw new Error(`Unexpected carousel dependency: ${input}`);
}
const bundle = built.outputFiles[0]?.text;
if (!bundle) throw new Error('No carousel bundle.');
const banner = `/*! CraftKit carousel — embla-carousel@${manifest.version} (MIT)\n${license.replaceAll('*/', '* /')}\n*/\n`;
const source = banner + bundle;
const bytes = gzipSync(source).byteLength;
if (bytes > 20_000) throw new Error(`Carousel gzip budget exceeded: ${bytes}/20000`);
const digest = createHash('sha256').update(source).digest('hex');
writeFileSync(
  join(root, 'packages/builder/renderer/src/engines/carousel-source.ts'),
  `/* GENERATED by node scripts/build-carousel-engine.mjs. MIT notice travels with the asset. */\nexport const CAROUSEL_VERSION = ${JSON.stringify(manifest.version)};\nexport const CAROUSEL_SHA256 = ${JSON.stringify(digest)};\nexport const CAROUSEL_SOURCE: string = ${JSON.stringify(source)};\n`,
);
console.log(`Embla ${manifest.version}: ${bytes} bytes gzip, sha256 ${digest}`);
